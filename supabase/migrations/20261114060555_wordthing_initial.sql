-- Only Word-Thing Cloud objects are created here; phototeam remains untouched.
CREATE SCHEMA IF NOT EXISTS wordthing;
REVOKE ALL ON SCHEMA wordthing FROM PUBLIC, anon, authenticated;
CREATE TABLE wordthing.rooms(id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, code text UNIQUE NOT NULL, name text NOT NULL, banned text NOT NULL DEFAULT '[]', created timestamptz DEFAULT now());
CREATE TABLE wordthing.activities(id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, room_id integer NOT NULL REFERENCES wordthing.rooms(id) ON DELETE CASCADE, topic text NOT NULL, mode text NOT NULL CHECK (mode IN ('live','hidden')), word_limit integer, status text NOT NULL DEFAULT 'open' CHECK (status IN ('open','stopped','closed')), revealed integer NOT NULL DEFAULT 0 CHECK (revealed IN (0,1)), created timestamptz DEFAULT now());
CREATE TABLE wordthing.participants(id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, room_id integer NOT NULL REFERENCES wordthing.rooms(id) ON DELETE CASCADE, affiliation text NOT NULL, name text NOT NULL, nickname text NOT NULL, nickname_key text NOT NULL, salt text NOT NULL, pin_hash text NOT NULL, banned integer NOT NULL DEFAULT 0 CHECK (banned IN (0,1)), UNIQUE(room_id,nickname_key));
CREATE TABLE wordthing.activity_participants(activity_id integer NOT NULL REFERENCES wordthing.activities(id) ON DELETE CASCADE, participant_id integer NOT NULL REFERENCES wordthing.participants(id) ON DELETE CASCADE, PRIMARY KEY(activity_id,participant_id));
CREATE TABLE wordthing.words(id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, activity_id integer NOT NULL REFERENCES wordthing.activities(id) ON DELETE CASCADE, participant_id integer NOT NULL REFERENCES wordthing.participants(id) ON DELETE CASCADE, word text NOT NULL, word_key text NOT NULL, created timestamptz DEFAULT now(), UNIQUE(activity_id,participant_id,word_key));
CREATE TABLE wordthing.sessions(token text PRIMARY KEY, role text NOT NULL CHECK (role IN ('admin','participant')), participant_id integer REFERENCES wordthing.participants(id) ON DELETE CASCADE, created bigint NOT NULL);
CREATE INDEX ON wordthing.activities(room_id,id DESC);
CREATE INDEX ON wordthing.participants(room_id);
CREATE INDEX ON wordthing.words(activity_id);
CREATE INDEX ON wordthing.sessions(participant_id);
ALTER TABLE wordthing.rooms ENABLE ROW LEVEL SECURITY;
ALTER TABLE wordthing.activities ENABLE ROW LEVEL SECURITY;
ALTER TABLE wordthing.participants ENABLE ROW LEVEL SECURITY;
ALTER TABLE wordthing.activity_participants ENABLE ROW LEVEL SECURITY;
ALTER TABLE wordthing.words ENABLE ROW LEVEL SECURITY;
ALTER TABLE wordthing.sessions ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON ALL TABLES IN SCHEMA wordthing FROM PUBLIC, anon, authenticated;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA wordthing FROM PUBLIC, anon, authenticated;
-- Provision an application login separately; grant only this schema and create
-- explicit RLS policies for that login. Never grant access to phototeam.
CREATE TABLE wordthing.presence(session_token text PRIMARY KEY REFERENCES wordthing.sessions(token) ON DELETE CASCADE, expires_at bigint NOT NULL);
CREATE TABLE wordthing.login_attempts(subject text NOT NULL, bucket bigint NOT NULL, attempts integer NOT NULL, PRIMARY KEY(subject,bucket));
CREATE INDEX ON wordthing.presence(expires_at);
ALTER TABLE wordthing.presence ENABLE ROW LEVEL SECURITY;
ALTER TABLE wordthing.login_attempts ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON wordthing.presence,wordthing.login_attempts FROM PUBLIC,anon,authenticated;
-- Shared-project isolation: runtime role has no privileges on phototeam.
-- The LOGIN role/password must be provisioned separately and granted membership
-- in wordthing_runtime. Never connect using a postgres or service-role secret.
DO $$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname='wordthing_runtime') THEN
    CREATE ROLE wordthing_runtime NOLOGIN;
  END IF;
END $$;
GRANT USAGE ON SCHEMA wordthing TO wordthing_runtime;
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA wordthing TO wordthing_runtime;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA wordthing TO wordthing_runtime;
DO $$ DECLARE table_name text; BEGIN
  FOREACH table_name IN ARRAY ARRAY['rooms','activities','participants','activity_participants','words','sessions','presence','login_attempts'] LOOP
    EXECUTE format('CREATE POLICY wordthing_runtime_access ON wordthing.%I TO wordthing_runtime USING (true) WITH CHECK (true)',table_name);
  END LOOP;
END $$;

-- The trigger is deliberately limited to an empty invalidation signal. The
-- private SECURITY DEFINER function is not exposed to browser roles and cannot
-- be called as an API; it never broadcasts records, names, PINs or hidden words.
CREATE OR REPLACE FUNCTION wordthing.emit_changed() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog, wordthing AS $$
DECLARE target_code text; target_room integer;
BEGIN
  IF TG_TABLE_NAME='rooms' THEN
    target_code := COALESCE(NEW.code, OLD.code);
  ELSIF TG_TABLE_NAME IN ('activities','participants') THEN
    target_room := COALESCE(NEW.room_id, OLD.room_id);
  ELSIF TG_TABLE_NAME='words' THEN
    SELECT a.room_id INTO target_room FROM wordthing.activities a WHERE a.id=COALESCE(NEW.activity_id, OLD.activity_id);
  END IF;
  IF target_code IS NULL AND target_room IS NOT NULL THEN
    SELECT r.code INTO target_code FROM wordthing.rooms r WHERE r.id=target_room;
  END IF;
  IF target_code IS NOT NULL THEN
    PERFORM realtime.send('{}'::jsonb, 'changed', 'wordthing-room-' || target_code, false);
  END IF;
  RETURN COALESCE(NEW,OLD);
END $$;
REVOKE ALL ON FUNCTION wordthing.emit_changed() FROM PUBLIC, anon, authenticated;
CREATE TRIGGER wordthing_room_changed AFTER INSERT OR UPDATE OR DELETE ON wordthing.rooms FOR EACH ROW EXECUTE FUNCTION wordthing.emit_changed();
CREATE TRIGGER wordthing_activity_changed AFTER INSERT OR UPDATE OR DELETE ON wordthing.activities FOR EACH ROW EXECUTE FUNCTION wordthing.emit_changed();
CREATE TRIGGER wordthing_participant_changed AFTER INSERT OR UPDATE OR DELETE ON wordthing.participants FOR EACH ROW EXECUTE FUNCTION wordthing.emit_changed();
CREATE TRIGGER wordthing_word_changed AFTER INSERT OR UPDATE OR DELETE ON wordthing.words FOR EACH ROW EXECUTE FUNCTION wordthing.emit_changed();
